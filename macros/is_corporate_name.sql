{#
  商号に法人の種類（株式会社・(株)・合同会社・医療法人・協同組合など）が入っていれば true。
  建設業・宅建業の一覧には法人・個人の区分が無いので、これで個人事業主を除く。
  東京都の建設業許可業者名簿（法人・個人の区分あり）で確かめると、個人の商号はどれも当たらず、
  漏れる法人は名前に種類の入らない外国法人だけだった
#}
{% macro is_corporate_name(column) %}
regexp_matches(
    {{ column }},
    '株式会社|有限会社|合同会社|合資会社|合名会社|相互会社|\((株|有|同|資|名|合|医|社|財|学|福|宗|協|企|特非|一社|一財|公社|公財|NPO)\)|法人|組合|公社|機構|事業団|協会|連合会|信用金庫|銀行'
)
{% endmacro %}
